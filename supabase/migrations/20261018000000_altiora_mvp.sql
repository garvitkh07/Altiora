create or replace function public.is_restaurant_member(p_restaurant_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.restaurant_members as rm
    where rm.restaurant_id = p_restaurant_id
      and rm.user_id = auth.uid()
  );
$$;

create or replace function public.is_restaurant_manager(p_restaurant_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.restaurant_members as rm
    where rm.restaurant_id = p_restaurant_id
      and rm.user_id = auth.uid()
      and rm.role in ('OWNER', 'MANAGER')
  );
$$;

