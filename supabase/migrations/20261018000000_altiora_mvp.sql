-- Altiora MVP schema, tenant isolation, public-menu lookup, and order RPC.
--
-- The browser uses the public Supabase anon key. No service-role key is needed:
-- public menu access is exposed through get_public_menu(), and order creation is
-- exposed through the atomic create_order() function. Both functions validate
-- active restaurant/table/menu state inside the database.

create extension if not exists pgcrypto;

create type public.member_role as enum ('OWNER', 'MANAGER', 'STAFF');
create type public.order_status as enum ('NEW', 'PREPARING', 'READY', 'SERVED', 'CANCELLED');

create table public.restaurants (
  id uuid primary key default gen_random_uuid(),
  name text not null check (btrim(name) <> ''),
  slug text not null unique check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  description text,
  logo_url text,
  address text,
  phone text,
  currency text not null default 'INR' check (currency ~ '^[A-Z]{3}$'),
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table public.restaurant_members (
  id uuid primary key default gen_random_uuid(),
  restaurant_id uuid not null references public.restaurants(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role public.member_role not null default 'STAFF',
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  unique (restaurant_id, user_id),
  unique (id, restaurant_id)
);

create table public.categories (
  id uuid primary key default gen_random_uuid(),
  restaurant_id uuid not null references public.restaurants(id) on delete cascade,
  name text not null check (btrim(name) <> ''),
  description text,
  sort_order integer not null default 0 check (sort_order >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  unique (id, restaurant_id),
  unique (restaurant_id, name)
);

create table public.menu_items (
  id uuid primary key default gen_random_uuid(),
  restaurant_id uuid not null references public.restaurants(id) on delete cascade,
  category_id uuid not null,
  name text not null check (btrim(name) <> ''),
  description text,
  price numeric(10,2) not null check (price >= 0),
  original_price numeric(10,2) check (original_price is null or original_price >= price),
  is_veg boolean not null default false,
  is_available boolean not null default true,
  image_url text,
  allergens text[] not null default '{}',
  sort_order integer not null default 0 check (sort_order >= 0),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  unique (id, restaurant_id),
  foreign key (category_id, restaurant_id)
    references public.categories(id, restaurant_id)
    on delete restrict
);

create table public.restaurant_tables (
  id uuid primary key default gen_random_uuid(),
  restaurant_id uuid not null references public.restaurants(id) on delete cascade,
  label text not null check (btrim(label) <> ''),
  qr_token text not null unique default encode(gen_random_bytes(16), 'hex'),
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  unique (id, restaurant_id),
  unique (restaurant_id, label)
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  restaurant_id uuid not null references public.restaurants(id) on delete restrict,
  table_id uuid not null,
  created_by uuid references auth.users(id) on delete set null,
  status public.order_status not null default 'NEW',
  subtotal_amount numeric(12, 2) not null check (subtotal_amount >= 0),
  tax_amount numeric(12, 2) not null default 0 check (tax_amount >= 0),
  total_amount numeric(12, 2) not null check (total_amount = subtotal_amount + tax_amount),
  special_instructions text check (
    special_instructions is null or char_length(special_instructions) <= 500
  ),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  unique (id, restaurant_id),
  foreign key (table_id, restaurant_id)
    references public.restaurant_tables(id, restaurant_id)
    on delete restrict
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null,
  restaurant_id uuid not null,
  menu_item_id uuid not null,
  item_name_snapshot text not null check (btrim(item_name_snapshot) <> ''),
  unit_price_snapshot numeric(10,2) not null check (unit_price_snapshot >= 0),
  quantity smallint not null check (quantity between 1 and 99),
  line_total numeric(12, 2) not null check (
    line_total = round(unit_price_snapshot * quantity, 2)
  ),
  special_instructions text check (
    special_instructions is null or char_length(special_instructions) <= 500
  ),
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  unique (order_id, menu_item_id),
  foreign key (order_id, restaurant_id)
    references public.orders(id, restaurant_id)
    on delete cascade,
  foreign key (menu_item_id, restaurant_id)
    references public.menu_items(id, restaurant_id)
    on delete restrict
);

create index restaurants_active_idx
  on public.restaurants (id)
  where is_active;
create index restaurant_members_user_idx
  on public.restaurant_members (user_id, restaurant_id);
create index categories_active_idx
  on public.categories (restaurant_id, sort_order)
  where is_active;
create index menu_items_active_idx
  on public.menu_items (restaurant_id, category_id, sort_order)
  where is_available;
create index restaurant_tables_active_idx
  on public.restaurant_tables (restaurant_id, label)
  where is_active;
create index orders_restaurant_status_idx
  on public.orders (restaurant_id, status, created_at desc);
create index orders_table_created_idx
  on public.orders (table_id, created_at desc);
create index order_items_order_idx
  on public.order_items (order_id, created_at);
create index order_items_restaurant_idx
  on public.order_items (restaurant_id, order_id);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

revoke all on function public.set_updated_at() from public;

create or replace function public.prevent_order_immutable_updates()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.id is distinct from old.id
    or new.order_number is distinct from old.order_number
    or new.restaurant_id is distinct from old.restaurant_id
    or new.table_id is distinct from old.table_id
    or new.created_by is distinct from old.created_by
    or new.created_at is distinct from old.created_at
    or new.subtotal_amount is distinct from old.subtotal_amount
    or new.tax_amount is distinct from old.tax_amount
    or new.total_amount is distinct from old.total_amount
    or new.special_instructions is distinct from old.special_instructions then
    raise exception 'Only an order status may be changed' using errcode = 'P0001';
  end if;

  return new;
end;
$$;

revoke all on function public.prevent_order_immutable_updates() from public;

