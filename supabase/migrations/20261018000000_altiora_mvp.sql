create or replace function public.get_public_menu(
  p_restaurant_slug text,
  p_table_token text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_menu jsonb;
begin
  select jsonb_build_object(
    'restaurant', jsonb_build_object(
      'id', r.id,
      'name', r.name,
      'slug', r.slug,
      'description', r.description,
      'logo_url', r.logo_url,
      'address', r.address,
      'phone', r.phone
    ),
    'currency', r.currency,
    'table', jsonb_build_object(
      'id', rt.id,
      'label', rt.label
    ),
    'categories', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'id', c.id,
          'name', c.name,
          'description', c.description
        )
        order by c.sort_order, c.name
      )
      from public.categories as c
      where c.restaurant_id = r.id
        and c.is_active
    ), '[]'::jsonb),
    'items', coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'id', mi.id,
          'name', mi.name,
          'description', mi.description,
          'category_id', mi.category_id,
          'price', mi.price,
          'original_price', mi.original_price,
          'is_veg', mi.is_veg,
          'is_available', mi.is_available,
          'image_url', mi.image_url,
          'allergens', mi.allergens
        )
        order by mi.sort_order, mi.name
      )
      from public.menu_items as mi
      join public.categories as c
        on c.id = mi.category_id
       and c.restaurant_id = mi.restaurant_id
      where mi.restaurant_id = r.id
        and mi.is_available
        and c.is_active
    ), '[]'::jsonb)
  )
  into v_menu
  from public.restaurants as r
  join public.restaurant_tables as rt
    on rt.restaurant_id = r.id
  where r.slug = btrim(p_restaurant_slug)
    and r.is_active
    and rt.qr_token = btrim(p_table_token)
    and rt.is_active;

  if v_menu is null then
    raise exception 'The menu or table is not available' using errcode = 'P0001';
  end if;

  return v_menu;
end;
$$;

revoke all on function public.get_public_menu(text, text) from public;
grant execute on function public.get_public_menu(text, text) to anon, authenticated;

create or replace function public.create_order(
  p_restaurant_slug text,
  p_table_token text,
  p_items jsonb,
  p_special_instructions text default null
)
returns table (
  order_id uuid,
  order_number bigint,
  status public.order_status,
  total_amount numeric(12, 2)
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_item jsonb;
  v_menu_item_id uuid;
  v_item_name text;
  v_unit_price numeric(10, 2);
  v_quantity integer;
  v_item_instructions text;
  v_restaurant_id uuid;
  v_table_id uuid;
  v_order_id uuid;
  v_order_number bigint;
  v_total numeric(12, 2) := 0;
  v_seen_item_ids uuid[] := '{}'::uuid[];
  v_order_instructions text := nullif(btrim(p_special_instructions), '');
begin
  if p_restaurant_slug is null or btrim(p_restaurant_slug) = ''
    or p_table_token is null or btrim(p_table_token) = '' then
    raise exception 'A restaurant slug and table token are required' using errcode = 'P0001';
  end if;

  if p_items is null or jsonb_typeof(p_items) <> 'array'
    or jsonb_array_length(p_items) < 1 then
    raise exception 'At least one item is required' using errcode = 'P0001';
  end if;

  if jsonb_array_length(p_items) > 50 then
    raise exception 'An order cannot contain more than 50 items' using errcode = 'P0001';
  end if;

  if v_order_instructions is not null and char_length(v_order_instructions) > 500 then
    raise exception 'Special instructions cannot exceed 500 characters' using errcode = 'P0001';
  end if;

  select r.id, rt.id
    into v_restaurant_id, v_table_id
  from public.restaurants as r
  join public.restaurant_tables as rt
    on rt.restaurant_id = r.id
  where r.slug = btrim(p_restaurant_slug)
    and r.is_active
    and rt.qr_token = btrim(p_table_token)
    and rt.is_active
  for update of r, rt;

  if not found then
    raise exception 'The restaurant or table is not available' using errcode = 'P0001';
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    if jsonb_typeof(v_item) <> 'object'
      or not (v_item ? 'menu_item_id')
      or not (v_item ? 'quantity')
      or jsonb_typeof(v_item -> 'menu_item_id') <> 'string'
      or jsonb_typeof(v_item -> 'quantity') <> 'number'
      or (v_item ? 'special_instructions' and jsonb_typeof(v_item -> 'special_instructions') not in ('string', 'null'))
      or (
        select count(*)
        from jsonb_object_keys(v_item) as keys(key)
        where key not in ('menu_item_id', 'quantity', 'special_instructions')
      ) > 0 then
      raise exception 'Each item needs a menu_item_id and quantity' using errcode = 'P0001';
    end if;

    begin
      v_menu_item_id := (v_item ->> 'menu_item_id')::uuid;
    exception when invalid_text_representation then
      raise exception 'A valid menu item is required' using errcode = 'P0001';
    end;

    begin
      v_quantity := (v_item ->> 'quantity')::integer;
    exception when invalid_text_representation then
      raise exception 'Quantity must be an integer between 1 and 99' using errcode = 'P0001';
    end;

    if v_quantity < 1 or v_quantity > 99 then
      raise exception 'Quantity must be an integer between 1 and 99' using errcode = 'P0001';
    end if;

    v_item_instructions := nullif(btrim(v_item ->> 'special_instructions'), '');
    if v_item_instructions is not null and char_length(v_item_instructions) > 500 then
      raise exception 'Special instructions cannot exceed 500 characters' using errcode = 'P0001';
    end if;

    if v_menu_item_id = any(v_seen_item_ids) then
      raise exception 'Each menu item may appear only once' using errcode = 'P0001';
    end if;
    v_seen_item_ids := array_append(v_seen_item_ids, v_menu_item_id);

    select mi.name, mi.price
      into v_item_name, v_unit_price
    from public.menu_items as mi
    join public.categories as c
      on c.id = mi.category_id
     and c.restaurant_id = mi.restaurant_id
    where mi.id = v_menu_item_id
      and mi.restaurant_id = v_restaurant_id
      and mi.is_available
      and c.is_active
    for update of mi;

    if not found then
      raise exception 'A menu item is not available' using errcode = 'P0001';
    end if;

    v_total := v_total + round(v_unit_price * v_quantity, 2);
  end loop;

  insert into public.orders (
    restaurant_id,
    table_id,
    created_by,
    status,
    subtotal_amount,
    tax_amount,
    total_amount,
    special_instructions
  ) values (
    v_restaurant_id,
    v_table_id,
    auth.uid(),
    'NEW',
    v_total,
    0,
    v_total,
    v_order_instructions
  )
  returning id, order_number
    into v_order_id, v_order_number;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_menu_item_id := (v_item ->> 'menu_item_id')::uuid;
    v_quantity := (v_item ->> 'quantity')::integer;
    v_item_instructions := nullif(btrim(v_item ->> 'special_instructions'), '');

    select mi.name, mi.price
      into v_item_name, v_unit_price
    from public.menu_items as mi
    where mi.id = v_menu_item_id
      and mi.restaurant_id = v_restaurant_id;

    insert into public.order_items (
      order_id,
      restaurant_id,
      menu_item_id,
      item_name_snapshot,
      unit_price_snapshot,
      quantity,
      line_total,
      special_instructions
    ) values (
      v_order_id,
      v_restaurant_id,
      v_menu_item_id,
      v_item_name,
      v_unit_price,
      v_quantity,
      round(v_unit_price * v_quantity, 2),
      v_item_instructions
    );
  end loop;

  return query
  select v_order_id, v_order_number, 'NEW'::public.order_status, v_total;
end;
$$;

revoke all on function public.create_order(text, text, jsonb, text) from public;
grant execute on function public.create_order(text, text, jsonb, text) to anon, authenticated;
